<h2>Statement of Compliance</h2>
<p>We (SAI ALUPACK LTD.) declare that all kinds of Food Packaging Products manufactured are in
compliance with all the National/ International Food Contact Material standards 21 CFR 177.1500, CM/Res(2013)9
legal regulation laid down in (EU) No.10/2011 [Amendment EU 2020/1245 of Regulation (EU) No 10/2011], Regulation
(EC) No 1935/2004 (Resolution ResAP (2002) Industry Guideline and Board Food Packaging Chain), (EC) No.
2023/2006, Food and feed act (LFGB, §§ 30, 31)] and The Materials and Articles in Contact with Food (England,
Wales, Scotland, Ireland) Regulations 2012 (No.2619; 2705, 318, 384).</p>
<p>When used as speciﬁed, the overall migration, as well as the speciﬁc migration, does not exceed the legal limits. The
test will be performed According to the Directives 82/711/EEC and 85/572/EEC as well as According to Articles 17 and
18 of Regulation (EU) No. 10/2011 in conjunction with Annex V the Materials and raw materials used comply with
Regulation (EU) No 10/2011. All products supplied comply with Packaging (Essential Requirements) Regulations 2003
and its subsequent legislations. All types of food packaging products developed are made under strict hygienic
conditions and food-grade materials are used for their manufacture. They comply with the migration test with Food
Stimulants (A, B, C, D1, D2) as per the protocol of the test method for Overall Migration and Speciﬁc Migration, and all
results are within the limits in Regulation (EU) No. 10/2011 as well as for Regulation (EC) No 1935/2004 the sampling
range per piece.</p>
<p>All these products are free from Physical, Chemical, Biological, and Allergenic Contaminants and comply with REACH
Regulation EC 1907/2006 and any subsequent amendments; and can state that our products do not contain
“substances of very high concern” (SVHC) > 0.1 % according to the current ECHA candidate list. For the Aluminium
products, we declare that our products comply with Council of Europe Resolution CM/Res(2013)9 on metals and
alloys used in food contact materials and articles. All articles delivered abide by the requirements of Directive
94/62/EC (“Packaging directive”) and the accumulated amount of lead, cadmium, mercury, and chromium (VI) does
not exceed 100 mg/kg.</p>
<p>All the paper raw materials used are procured from responsible sources and are subjected to supplier evaluation. As
part of ensuring a sustainable model of aluminium material usage. All aluminium materials for food contact abide by
the BfR-Recommendation XXXVI. For all the delivered items, we declare that no PFAS (per- and poly-ﬂuoroalkyl
substances) are intentionally used in the products supplied. The base material used may include post-consumer
recycled aluminium however they are recycled to achieve the expected purity and as evidenced by the supplier SOC
and subsequent migration result. The shelf-life of the product from the date of manufacture will be for 2 years and
the products are meant for single use.</p>

